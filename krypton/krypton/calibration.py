"""Calibration report (spec §11): how the placeholder thresholds get replaced with real ones."""

from __future__ import annotations

import csv
import io
from dataclasses import dataclass
from math import ceil

from krypton.schemas import EngineResult, FunctionFinding

PERCENTILES = (50, 75, 90, 95, 99, 100)
THRESHOLDS = (40, 100, 300, 1_000, 3_000, 10_000)
METRICS = ("rating_master", "rating_nesting", "score", "branches", "max_depth", "effective_lines")
CSV_FIELDS = ("filename", *FunctionFinding.model_fields)


def calibration_report(by_mode: dict[str, EngineResult]) -> str:
    """by_mode holds the same scan run once per rating mode ("master", "nesting")."""
    result = by_mode["master"]
    functions = [function for finding in result.findings for function in finding.functions]
    lines = [f"Calibration over {len(functions)} functions in {len(result.findings)} files", ""]
    lines.append(f"{'metric':<16}" + "".join(f"{_label(p):>12}" for p in PERCENTILES))
    for metric in METRICS:
        values = sorted(float(getattr(function, metric)) for function in functions)
        lines.append(f"{metric:<16}" + "".join(f"{_percentile(values, p):>12.1f}" for p in PERCENTILES))
    lines += ["", f"{'threshold':>10} {'fn master':>10} {'fn nesting':>11} {'file master':>12} {'file nesting':>13}"]
    for threshold in THRESHOLDS:
        lines.append(
            f"{threshold:>10,} {_share(functions, 'rating_master', threshold):>10.1%} "
            f"{_share(functions, 'rating_nesting', threshold):>11.1%} "
            f"{_file_share(by_mode['master'], threshold):>12.1%} {_file_share(by_mode['nesting'], threshold):>13.1%}"
        )
    lines += ["", "purity score: " + ", ".join(f"{mode} {run.purity_score}" for mode, run in by_mode.items())]
    return "\n".join(lines)


def calibration_csv(result: EngineResult) -> str:
    """One row per function with every metric, for comparing repos side by side."""
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=CSV_FIELDS, lineterminator="\n")
    writer.writeheader()
    for finding in result.findings:
        for function in finding.functions:
            writer.writerow({"filename": finding.filename, **function.model_dump()})
    return buffer.getvalue()


@dataclass(frozen=True)
class ModeFit:
    """A fitted threshold for one rating mode and how well it separates agentic from human functions."""

    mode: str
    threshold: float
    agentic_flagged: float  # share of agentic functions rated above the threshold
    human_flagged: float  # share of human functions rated above the threshold

    @property
    def separation(self) -> float:
        """Youden's J: how much better than chance the threshold tells the two apart."""
        return self.agentic_flagged - self.human_flagged


def fit_thresholds(human: list[dict[str, str]], agentic: list[dict[str, str]]) -> dict[str, ModeFit]:
    """Per rating mode, the threshold that flags the most agentic and fewest human functions."""
    return {mode: _fit_mode(mode, human, agentic) for mode in ("master", "nesting")}


def best_mode(fits: dict[str, ModeFit]) -> ModeFit:
    """Higher separation wins; a tie keeps the spec's default, "master"."""
    return max(fits.values(), key=lambda fit: (fit.separation, fit.mode == "master"))


def _fit_mode(mode: str, human: list[dict[str, str]], agentic: list[dict[str, str]]) -> ModeFit:
    """Try every observed rating as the threshold; keep the best separation (higher on ties)."""
    column = f"rating_{mode}"
    human_values = [float(row[column]) for row in human]
    agentic_values = [float(row[column]) for row in agentic]
    candidates = sorted({0.0, *human_values, *agentic_values})
    fits = [
        ModeFit(mode, threshold, _above(agentic_values, threshold), _above(human_values, threshold))
        for threshold in candidates
    ]
    # Best separation; on a tie the higher threshold, so fewer functions are flagged.
    return max(fits, key=lambda fit: (fit.separation, fit.threshold))


def _above(values: list[float], threshold: float) -> float:
    """Share of values strictly above the threshold (0.0 when there are none)."""
    return sum(value > threshold for value in values) / len(values) if values else 0.0


def calibrated_module(fits: dict[str, ModeFit], sources: dict[str, str], counts: dict[str, int]) -> str:
    """Source for krypton/engine/calibrated.py: the fitted values, so config.py has no magic 40."""
    chosen = best_mode(fits)
    lines = [
        '"""Calibrated thresholds. Generated by `python -m krypton.cli --fit-thresholds`; do not edit by hand.',
        "",
        f"Human data:   {sources['human']} ({counts['human']} functions)",
        f"Agentic data: {sources['agentic']} ({counts['agentic']} functions)",
    ]
    lines += [
        f"{fit.mode:>8}: threshold {fit.threshold:g} flags {fit.agentic_flagged:.0%} of agentic, "
        f"{fit.human_flagged:.0%} of human functions (separation {fit.separation:.2f})"
        for fit in fits.values()
    ]
    lines += [
        '"""',
        "",
        f'RATING_MODE = "{chosen.mode}"',
        f"SEMANTIC_PATH_FLAG_THRESHOLD = {fits['master'].threshold!r}",
        f"NESTING_FLAG_THRESHOLD = {fits['nesting'].threshold!r}",
        "",
    ]
    return "\n".join(lines)


def read_csv(text: str) -> list[dict[str, str]]:
    """Rows of a --calibrate-out CSV, as dicts keyed by column name."""
    return list(csv.DictReader(io.StringIO(text)))


def _percentile(sorted_values: list[float], percentile: int) -> float:
    """Nearest-rank percentile; 100 is the max."""
    if not sorted_values:
        return 0.0
    rank = max(1, ceil(percentile / 100 * len(sorted_values)))
    return sorted_values[rank - 1]


def _label(percentile: int) -> str:
    """Column label for a percentile: p50 ... p99, or max for 100."""
    return "max" if percentile == 100 else f"p{percentile}"


def _share(functions: list[FunctionFinding], metric: str, threshold: float) -> float:
    """Share of functions whose metric is above the threshold."""
    if not functions:
        return 0.0
    return sum(getattr(function, metric) > threshold for function in functions) / len(functions)


def _file_share(result: EngineResult, threshold: float) -> float:
    """Share of files whose active-mode rating is above the threshold."""
    if not result.findings:
        return 0.0
    return sum(finding.logic_complexity_rating > threshold for finding in result.findings) / len(result.findings)
